def c_header():
    out = [HEAD, "#pragma once\n"]
    for n, v in COLOR.items():
        key = n.upper().replace("-", "_")
        out.append(f'#define PITALOKA_{key}_LIGHT "{v["light"]}"')
        out.append(f'#define PITALOKA_{key}_DARK  "{v["dark"]}"')
    out.append("")
    for group, data in (("RADIUS", RADIUS), ("SPACE", SPACE), ("METRIC", METRIC)):
        for n, v in data.items():
            out.append(f"#define PITALOKA_{group}_{n.upper().replace('-', '_')} {v['value']}")
        out.append("")
    return "\n".join(out)


def tokens_md():
    out = ["<!-- Generated by build/generate.py from tokens/tokens.json. Do not edit by hand. -->",
           f"# {T['$meta']['name']} — token reference", "", f"Version {T['$meta']['version']}.", ""]

    out += ["## Color", "", "| Token | Light | Dark | Use |", "| --- | --- | --- | --- |"]
    for n, v in COLOR.items():
        out.append(f"| `--pit-{n}` | `{v['light']}` | `{v['dark']}` | {v['use']} |")

    out += ["", "## Typography", "", "| Step | Size | Weight | Tracking | Family | Use |", "| --- | --- | --- | --- | --- | --- |"]
    for n, v in T["type"].items():
        out.append(f"| `{n}` | {v['size']}px | {v['weight']} | {v['tracking']} | {FONT[v['font']]} | {v['use']} |")

    for title, prefix, data in (("Radius", "--pit-radius-", RADIUS),
                                ("Spacing", "--pit-space-", SPACE),
                                ("Metrics", "--pit-", METRIC)):
        out += ["", f"## {title}", "", "| Token | Value | Use |", "| --- | --- | --- |"]
        for n, v in data.items():
            out.append(f"| `{prefix}{n}` | {v['value']}px | {v['use']} |")

    out += ["", "## Elevation", "", "| Token | Shadow | Use |", "| --- | --- | --- |"]
    for n, v in ELEV.items():
        out.append(f"| `--pit-elevation-{n}` | `{v['shadow']}` | {v['use']} |")

    out += ["", "## States", "", "| State | Rule |", "| --- | --- |"]
    for n, v in T["state"].items():
        out.append(f"| `{n}` | {v} |")

    out += ["", "## Fonts", "", f"- UI: **{FONT['ui']}**", f"- Mono: **{FONT['mono']}**", ""]
    return "\n".join(out)


def main():
    outputs = {
        ROOT / "tokens" / "pitaloka-web.css": web_css(),
        ROOT / "tokens" / "pitaloka.css": gtk_css(),
        ROOT / "tokens" / "pitaloka.qss": qt_qss(),
        ROOT / "tokens" / "pitaloka.h": c_header(),
        ROOT / "TOKENS.md": tokens_md(),
        ROOT / "assets" / "tokens-data.js": "// Generated by build/generate.py. Do not edit by hand.\nwindow.PITALOKA_TOKENS = "
        + json.dumps(T, indent=2)
        + ";\n",
    }
    for path, body in outputs.items():
        path.write_text(body)
        print("wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    main()
